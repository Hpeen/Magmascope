export function t(key, lang) {
  const dict = I18N[lang] || I18N.en;
  if (key in dict) return dict[key];
  if (key in I18N.en) return I18N.en[key];
  return key;
}

export function tFallback(prefix, value, lang) {
  const key = prefix + '.' + value;
  const dict = I18N[lang] || I18N.en;
  if (key in dict) return dict[key];
  if (key in I18N.en) return I18N.en[key];
  return value;
}

const MONTHS_EN_RO = {
  January: 'Ianuarie', February: 'Februarie', March: 'Martie',
  April: 'Aprilie', May: 'Mai', June: 'Iunie',
  July: 'Iulie', August: 'August', September: 'Septembrie',
  October: 'Octombrie', November: 'Noiembrie', December: 'Decembrie',
};

const ERUPTION_SPECIAL_RO = {
  'Continuous': 'Continuă',
  'Continuous (Seepage)': 'Continuă (Scurgere)',
  'Long dormant': 'De mult timp inactiv',
  'Long extinct': 'De mult timp stins',
  'Ancient': 'Antică',
};

export function formatEruption(value, lang) {
  if (lang !== 'ro' || !value) return value;
  if (ERUPTION_SPECIAL_RO[value]) return ERUPTION_SPECIAL_RO[value];

  // "Month Year"  e.g. "March 1944"
  const monthYear = value.match(/^([A-Z][a-z]+)\s+(\d{4})$/);
  if (monthYear) {
    const ro = MONTHS_EN_RO[monthYear[1]];
    return ro ? `${ro} ${monthYear[2]}` : value;
  }

  // "~X AD" or "X AD"  →  "~X d.Hr."
  if (/^~?\d+\s+AD$/.test(value)) return value.replace(/\s+AD$/, ' d.Hr.');

  // "~X BC" or "X BC"  →  "~X î.Hr."
  if (/^~?\d+\s+BC$/.test(value)) return value.replace(/\s+BC$/, ' î.Hr.');

  // "~X,XXX years ago" / "~X years ago"
  const yearsAgo = value.match(/^(~?[\d,]+)\s+years?\s+ago$/i);
  if (yearsAgo) return `în urmă cu ${yearsAgo[1]} de ani`;

  // "~X million years ago"
  const millionYears = value.match(/^(~?[\d.]+)\s+million\s+years?\s+ago$/i);
  if (millionYears) return `în urmă cu ${millionYears[1]} milioane de ani`;

  return value;
}
